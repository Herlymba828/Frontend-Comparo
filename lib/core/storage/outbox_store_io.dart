import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:path_provider/path_provider.dart';

import 'outbox_store.dart';

OutboxStore createOutboxStore() => FileOutboxStore();

/// Files in the app's private support directory: entries in one JSON file,
/// each photo in its own file.
class FileOutboxStore implements OutboxStore {
  FileOutboxStore({Future<Directory> Function()? directory})
    : _directory = directory ?? getApplicationSupportDirectory;

  final Future<Directory> Function() _directory;

  Future<Directory> _root() async {
    final root = Directory('${(await _directory()).path}/outbox');
    await root.create(recursive: true);
    return root;
  }

  Future<File> _entriesFile() async =>
      File('${(await _root()).path}/entries.json');

  Future<File> _photoFile(String id) async {
    // Ids are generated by the app; refuse anything that could leave the folder.
    if (!RegExp(r'^[A-Za-z0-9-]+$').hasMatch(id)) {
      throw ArgumentError.value(id, 'id');
    }
    return File('${(await _root()).path}/$id.photo');
  }

  @override
  Future<List<Map<String, dynamic>>> readAll() async {
    final file = await _entriesFile();
    if (!await file.exists()) {
      return [];
    }
    final decoded = jsonDecode(await file.readAsString());
    return decoded is List
        ? decoded.whereType<Map<String, dynamic>>().toList()
        : [];
  }

  @override
  Future<void> writeAll(List<Map<String, dynamic>> entries) async {
    final file = await _entriesFile();
    // Written beside then renamed: a crash never leaves half a file.
    final temporary = File('${file.path}.tmp');
    await temporary.writeAsString(jsonEncode(entries), flush: true);
    await temporary.rename(file.path);
  }

  @override
  Future<void> savePhoto(String id, Uint8List bytes) async =>
      (await _photoFile(id)).writeAsBytes(bytes, flush: true);

  @override
  Future<Uint8List?> readPhoto(String id) async {
    final file = await _photoFile(id);
    return await file.exists() ? file.readAsBytes() : null;
  }

  @override
  Future<void> deletePhoto(String id) async {
    final file = await _photoFile(id);
    if (await file.exists()) {
      await file.delete();
    }
  }
}
